export const articlePath = (a: Article) => `/statii/${a.slug}/`;
const imageKey = (a: Article) => `statii/${a.slug}`;

const readingMinutes = (a: Article) => {
  const words = (a.lead + ' ' + a.body).replace(/<[^>]+>/g, ' ').split(/\s+/).filter(Boolean).length;
  return Math.max(2, Math.round(words / 200));
};

const formatDate = (ymd: string) => {
  const months = ['януари', 'февруари', 'март', 'април', 'май', 'юни', 'юли', 'август', 'септември', 'октомври', 'ноември', 'декември'];
  const [y, m, d] = ymd.split('-').map(Number);
  return `${d} ${months[m - 1]} ${y} г.`;
};

