export function findBreed(breedName: string): BreedInfo | null {
  if (!breedName) return null;
  const normalized = breedName.toLowerCase().trim();
  return breeds.find(b =>
    b.names.some(n => n.toLowerCase().includes(normalized) || normalized.includes(n.toLowerCase()))
  ) ?? null;
}

export function getWeightStatus(
  currentWeightKg: number,
  breed: BreedInfo,
  sex?: string
): { status: 'underweight' | 'ideal' | 'overweight' } {
  const range = sex?.toLowerCase() === 'female' ? breed.weightKg.female : breed.weightKg.male;
  const [min, max] = range;
  if (currentWeightKg < min * 0.9) return { status: 'underweight' };
  if (currentWeightKg > max * 1.1) return { status: 'overweight' };
  return { status: 'ideal' };
}

